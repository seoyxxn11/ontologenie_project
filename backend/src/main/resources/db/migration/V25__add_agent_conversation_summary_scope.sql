-- V25 Agent 대화 요약을 만든 권한 범위 (2026-11-14, S15P31C106-413)
-- 대화 요약은 만들 때의 열람 범위로 만든 사본이다. 그 뒤 범위가 줄면(유형 그룹이 빠짐, 민감 속성이 늘어남 등) 요약을 모델에
-- 다시 넘기지 않으려고, 요약을 저장할 때 그 범위를 함께 적는다.
-- =====================================================================

ALTER TABLE agent_conversation
    ADD COLUMN summary_access_scope text;

COMMENT ON COLUMN agent_conversation.summary_access_scope IS '요약을 만든 권한 범위(JSON: 원천 정책 지문, 보이는 유형마다 민감 값 열람 여부·민감 속성). 지금 범위가 이보다 줄었으면 요약을 모델에 넘기지 않고 다음 요약 때 버린다. NULL이면 이 기능 전에 만든 요약이다';
